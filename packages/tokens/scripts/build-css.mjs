// Emits CSS files from the compiled tokens so consumers can use the theme
// without JavaScript (SSR, static pages, non-React apps).
import { copyFileSync, writeFileSync } from 'node:fs';
import { cobaltThemePair, themePairs, themePairToCssString } from '../dist/index.js';

const header = '/* Generated by @sam.barfield/field-tokens. Do not edit. */\n';

// Default theme: Obsidian dark on :root, Architectural light under [data-theme="light"].
writeFileSync('dist/tokens.css', header + themePairToCssString(cobaltThemePair));

// One file per built-in pair, e.g. dist/themes/titanium-amber.css
import { mkdirSync } from 'node:fs';
mkdirSync('dist/themes', { recursive: true });
for (const pair of themePairs) {
  writeFileSync(`dist/themes/${pair.id}.css`, header + themePairToCssString(pair));
}

copyFileSync('src/tailwind.css', 'dist/tailwind.css');
console.log('field-tokens: wrote tokens.css, themes/*.css, tailwind.css');
